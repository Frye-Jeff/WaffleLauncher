// -----------------------------------------------------------------------------
// Dev-only: generates the README "Supported apps" list from src/apps.js, in
// the same grouped, alphabetical order as the options page.
//
//   npm run readme-apps   rewrite the list between the markers in README.md
//
// `npm run check` uses buildAppsSection() to fail when the README is stale.
// -----------------------------------------------------------------------------
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const README = join(ROOT, "README.md");
export const START = "<!-- apps:start (generated by `npm run readme-apps`; edit src/apps.js instead) -->";
export const END = "<!-- apps:end -->";

const { catalog } = await import(pathToFileURL(join(ROOT, "src", "catalog.js")).href);

// The Markdown that belongs between START and END.
export function buildAppsSection() {
  const lines = [];
  for (const service of catalog()) {
    lines.push(`### ${service.name}`, "");
    for (const section of service.sections) {
      const names = section.apps.map((app) => app.name).join(", ");
      lines.push(section.name ? `**${section.name} (${section.apps.length}):** ${names}.` : `${names}.`, "");
    }
  }
  return lines.join("\n").trimEnd();
}

// The README's current text between the markers, or null if they're missing.
export function currentAppsSection(text = readFileSync(README, "utf8")) {
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start < 0 || end < start) return null;
  return text.slice(start + START.length, end).trim();
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = readFileSync(README, "utf8");
  if (currentAppsSection(text) === null) {
    console.error(`README.md is missing the markers:\n${START}\n${END}`);
    process.exitCode = 1;
  } else {
    const start = text.indexOf(START) + START.length;
    const end = text.indexOf(END);
    writeFileSync(README, `${text.slice(0, start)}\n${buildAppsSection()}\n${text.slice(end)}`);
    console.log("README.md supported apps list updated.");
  }
}
